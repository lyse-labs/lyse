import type {
  DsManifest,
  ManifestComponent,
  ManifestExtractionEntry,
  ManifestProp,
  ManifestToken,
} from "../manifest/types.js";
import type { AuditResult } from "../types.js";

const MAX_TOKENS_PER_AXIS = 40;
const MAX_COMPONENTS = 40;

function moreLine(rest: number): string {
  return `- … and ${rest} more — run \`lyse manifest\` for the full set.`;
}

// Raw prop text comes straight from parsed TypeScript source (e.g. a
// multi-line union type or a template-literal type containing backticks) and
// is rendered inside a single Markdown code span. Collapsing whitespace keeps
// a multi-line type on one line, and sizing the backtick fence to one longer
// than the longest backtick run already in the value (CommonMark's escaping
// rule for code spans) keeps a literal backtick from prematurely closing it.
function collapseWhitespace(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

function codeSpan(value: string): string {
  const collapsed = collapseWhitespace(value);
  const longestBacktickRun = (collapsed.match(/`+/g) ?? []).reduce((max, run) => Math.max(max, run.length), 0);
  const fence = "`".repeat(longestBacktickRun + 1);
  const needsPadding = collapsed === "" || collapsed.startsWith("`") || collapsed.endsWith("`");
  return needsPadding ? `${fence} ${collapsed} ${fence}` : `${fence}${collapsed}${fence}`;
}

function groupTokensByAxis(tokens: ManifestToken[]): Map<ManifestToken["axis"], ManifestToken[]> {
  const groups = new Map<ManifestToken["axis"], ManifestToken[]>();
  for (const token of tokens) {
    const group = groups.get(token.axis);
    if (group) {
      group.push(token);
    } else {
      groups.set(token.axis, [token]);
    }
  }
  return groups;
}

function renderProp(prop: ManifestProp): string {
  const parts = [`${codeSpan(prop.name)}: ${codeSpan(prop.type ?? "unknown")}`];
  if (prop.optional) parts.push("optional");
  const defaultText = prop.default !== null ? collapseWhitespace(prop.default) : "";
  if (defaultText !== "") parts.push(`default: ${codeSpan(defaultText)}`);
  if (prop.variants !== null && prop.variants.length > 0) {
    parts.push(`variants: ${prop.variants.map((v) => codeSpan(v)).join(", ")}`);
  }
  return `  - ${parts.join(" — ")}`;
}

function renderComponentBlock(component: ManifestComponent): string[] {
  const lines = [
    `### ${component.name}`,
    `- Module: \`${component.module}\``,
    // Omitted rather than rendered as "unknown": the graph cannot resolve component
    // source paths yet, so the line would be noise on every component.
    ...(component.file === null ? [] : [`- File: \`${component.file}\``]),
    `- Design system component: ${component.isDesignSystem ? "yes" : "no"}`,
    `- Detection: \`${component.detection}\``,
    `- Usage count: ${component.usageCount}`,
    `- Stories: ${component.storyCount}`,
  ];
  if (component.props.length === 0) {
    lines.push(`- Props: none documented`);
  } else {
    lines.push(`- Props:`);
    lines.push(...component.props.map(renderProp));
  }
  return lines;
}

function renderExtractionWarnings(entries: ManifestExtractionEntry[]): string[] {
  const unhealthy = entries.filter((e) => e.status === "degraded" || e.status === "failed");
  if (unhealthy.length === 0) return [];
  const lines = [`## Extraction warnings`, ``];
  for (const entry of unhealthy) {
    const remediation = entry.remediation !== null ? ` — ${entry.remediation}` : "";
    lines.push(`- **${entry.extractor}**: ${entry.status}${remediation}`);
  }
  lines.push(``);
  return lines;
}

export function renderAgentsMd(manifest: DsManifest, result: AuditResult): string {
  return [
    `# AGENTS.md — Design System Contract`,
    ``,
    `> Auto-generated by Lyse v${result.toolVersion} on ${result.timestamp}.`,
    `> Token set: \`${manifest.tokenSetHash}\` (covers the token set only — component/prop changes don't move this hash).`,
    `> Do not hand-edit; re-run \`lyse agents\` to refresh.`,
    ``,
    ...renderExtractionWarnings(manifest.extraction.entries),
    ...renderStackSection(result.stack),
    ...renderTokensSection(manifest.tokens),
    ...renderComponentsSection(manifest.components),
    `## 4. Hard rules for AI-generated code`,
    `- Never use hardcoded colors. Always use one of the concrete tokens listed above.`,
    `- Never use native \`<button>\`, \`<input>\`, \`<select>\`, \`<textarea>\`, \`<a>\` when a DS equivalent exists.`,
    `- Always include \`alt\` on \`<img>\`, \`aria-label\` on icon-only buttons.`,
    `- Always ship a Storybook story with new DS components.`,
    ``,
    `## 5. Lyse contract`,
    `Scoring: \`${result.scoringVersion}\``,
    ``,
    "```",
    `schema: 1`,
    `rules_version: ${result.rulesVersion}`,
    `tool_version: ${result.toolVersion}`,
    `scoring_version: ${result.scoringVersion}`,
    `token_set_hash: ${manifest.tokenSetHash}`,
    `schema_version: ${manifest.schemaVersion}`,
    "```",
    ``,
  ].join("\n");
}

function renderStackSection(stack: string[]): string[] {
  const lines = [`## 1. Stack detected`];
  if (stack.length === 0) {
    lines.push(`None detected.`);
  } else {
    lines.push(...stack.map((s) => `- ${s}`));
  }
  lines.push(``);
  return lines;
}

function renderTokensSection(tokens: ManifestToken[]): string[] {
  const lines = [`## 2. Design tokens`, ``];
  if (tokens.length === 0) {
    lines.push(`None detected.`, ``);
    return lines;
  }
  for (const [axis, group] of groupTokensByAxis(tokens)) {
    lines.push(`### ${axis}`);
    const shown = group.slice(0, MAX_TOKENS_PER_AXIS);
    lines.push(...shown.map((t) => `- \`${t.id}\` → \`${t.value}\``));
    const rest = group.length - shown.length;
    if (rest > 0) lines.push(moreLine(rest));
    lines.push(``);
  }
  return lines;
}

function renderComponentsSection(components: ManifestComponent[]): string[] {
  const lines = [`## 3. Component contracts`, ``];
  if (components.length === 0) {
    lines.push(`None detected.`, ``);
    return lines;
  }
  const shown = components.slice(0, MAX_COMPONENTS);
  for (const component of shown) {
    lines.push(...renderComponentBlock(component), ``);
  }
  const rest = components.length - shown.length;
  if (rest > 0) lines.push(moreLine(rest), ``);
  return lines;
}
